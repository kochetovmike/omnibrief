"""Licence allowlist (design §5) and the attribution obligations each source carries (design §7).

This is the single source of truth for *which source types may ever be used*. A source type that
is not a key of SOURCE_LICENCES is rejected by config validation, even if an adapter exists.
`required_phrases` are strings that NOTICE.md must contain while that source is enabled;
`validate-config` and the test suite enforce this.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class SourceLicence:
    name: str
    licence: str
    required_phrases: tuple[str, ...]


NVD_NOTICE = "This product uses the NVD API but is not endorsed or certified by the NVD."
EPSS_NOTICE = "See EPSS at https://www.first.org/epss"
CC_BY_URL = "https://creativecommons.org/licenses/by/4.0/"

SOURCE_LICENCES: dict[str, SourceLicence] = {
    "cisa_kev": SourceLicence("CISA Known Exploited Vulnerabilities", "CC0 1.0", ("CISA",)),
    "nvd": SourceLicence("NVD (NIST)", "Public domain; NVD API Terms of Use", (NVD_NOTICE,)),
    "ghsa": SourceLicence(
        "GitHub Advisory Database", "CC-BY 4.0", ("GitHub Advisory Database", CC_BY_URL, "modified")
    ),
    "epss": SourceLicence("EPSS (FIRST)", "Free to use; attribution requested", (EPSS_NOTICE,)),
    # Optional (§5) — allowlisted, but no adapter yet; enabling them needs a licence re-check first.
    "euvd": SourceLicence("ENISA EUVD", "ENISA legal notice", ("ENISA",)),
    "cvelist": SourceLicence("CVE List (CVE Program)", "CVE Program Terms of Use", ("MITRE",)),
}

DISCLAIMER = (
    "Summaries are machine-generated by Omnibrief from the sources above and may contain errors. "
    "They are not endorsed by any source. Always check the linked original."
)


def short_rights(source_types: list[str]) -> str:
    """Short-form attribution for the Atom <rights> element."""
    parts = []
    if "cisa_kev" in source_types:
        parts.append("CISA KEV (CC0)")
    if "ghsa" in source_types:
        parts.append(f"GitHub Advisory Database (CC-BY 4.0, {CC_BY_URL}; summarised and modified)")
    if "epss" in source_types:
        parts.append(f"EPSS ({EPSS_NOTICE})")
    if "nvd" in source_types:
        parts.append(f"NVD ({NVD_NOTICE})")
    return "Data from: " + "; ".join(parts) + ". " + DISCLAIMER
