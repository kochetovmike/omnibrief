"""Build the channel-neutral Digest from filtered records: one LLM call, or a fallback."""

from __future__ import annotations

import json
import logging
import re
from datetime import datetime
from urllib.parse import urlsplit
from zoneinfo import ZoneInfo

from omnibrief.attribution import NVD_NOTICE
from omnibrief.config import Config, TopicConfig
from omnibrief.llm import SYSTEM_INSTRUCTION, LLMError, LLMProvider
from omnibrief.models import Digest, DigestItem, Vuln
from omnibrief.render import escape_md, sanitise

log = logging.getLogger(__name__)

DESCRIPTION_CHARS = 700
LINKS_PER_ITEM = 3


_SAFE_URL = re.compile(r"^https://[^\s()<>\[\]\"'`\\]+$")


def item_links(v: Vuln) -> list[str]:
    """Advisory page first, then a couple of references. URLs with characters that would break
    markdown link syntax are skipped rather than mangled."""
    page = v.advisory_page()
    others = [r for r in v.refs if r != page and _SAFE_URL.match(r)]
    return ([page] if page else []) + others[: LINKS_PER_ITEM - (1 if page else 0)]


def to_item(v: Vuln, summarised: bool = True) -> DigestItem:
    product = v.products[0] if v.products else ""
    return DigestItem(
        id=v.id,
        aliases=v.aliases,
        title=v.title or (v.description[:120] + ("…" if len(v.description) > 120 else "")),
        product=product,
        severity=v.severity,
        cvss=v.cvss,
        kev=v.kev,
        epss_percentile=v.epss_percentile,
        status=v.status,
        changes=v.changes,
        links=item_links(v),
        summarised=summarised,
    )


def record_for_prompt(v: Vuln) -> dict:
    rec = {
        "id": v.id,
        "aliases": v.aliases or None,
        "status": v.status,
        "changes": v.changes or None,
        "actively_exploited": v.kev or v.eu_exploited or None,
        "known_ransomware_use": v.kev_ransomware or None,
        "title": v.title or None,
        "products": v.products[:5] or None,
        "packages": [
            {"ecosystem": p.ecosystem, "name": p.name, "vulnerable": p.vulnerable_range, "patched": p.patched}
            for p in v.packages[:5]
        ]
        or None,
        "cvss": v.cvss,
        "severity": v.severity,
        "epss_percentile": round(v.epss_percentile, 4) if v.epss_percentile is not None else None,
        "description": v.description[:DESCRIPTION_CHARS] or None,
        "links": item_links(v),
    }
    return {k: val for k, val in rec.items() if val is not None}


def digest_title(topic: TopicConfig, now: datetime, tz: str) -> str:
    local = now.astimezone(ZoneInfo(tz))
    return f"{topic.title} — {local.strftime('%d %b %Y, %H:%M %Z')}"


def _badges(i: DigestItem) -> str:
    bits = []
    if i.kev:
        bits.append("actively exploited")
    if i.severity:
        bits.append(i.severity + (f" {i.cvss:.1f}" if i.cvss is not None else ""))
    if i.epss_percentile is not None and i.epss_percentile >= 0.9:
        bits.append(f"EPSS {i.epss_percentile * 100:.0f}th pct")
    if i.status == "updated":
        bits.append("updated")
    return ", ".join(bits)


def _bullet(i: DigestItem) -> str:
    links = " · ".join(f"[{urlsplit(u).hostname or 'link'}]({u})" for u in i.links)
    text = escape_md(i.title or i.product)
    badges = _badges(i)
    line = f"- **{i.id}**" + (f" ({badges})" if badges else "") + (f" — {text}" if text else "")
    if i.changes:
        line += " — " + escape_md("; ".join(i.changes))
    return line + (f" — {links}" if links else "")


def footer_md(cfg: Config) -> str:
    return (
        f"\n\n*Data from CISA KEV, NVD, the GitHub Advisory Database and EPSS — "
        f"[Sources & licences]({cfg.site.base}about.html). {NVD_NOTICE} "
        "Summaries are machine-generated by Omnibrief and may contain errors; "
        "always check the linked original.*"
    )


def build_digest(
    cfg: Config,
    topic: TopicConfig,
    vulns: list[Vuln],
    provider: LLMProvider | None,
    run_id: str,
    now: datetime,
) -> tuple[Digest, str]:
    """Returns (digest, llm_status) where llm_status is ok | fallback | not_configured."""
    limit = cfg.llm.max_input_items
    head, overflow = vulns[:limit], vulns[limit:]
    items = [to_item(v) for v in head] + [to_item(v, summarised=False) for v in overflow]
    own_urls = {cfg.site.base, f"{cfg.site.base}about.html"}
    allowed = {u for i in items for u in i.links} | own_urls

    body, status = None, "not_configured"
    if provider is not None:
        template = (cfg.root / topic.prompt_file).read_text(encoding="utf-8")
        records_json = json.dumps([record_for_prompt(v) for v in head], ensure_ascii=False, indent=1)
        try:
            body = provider.generate(SYSTEM_INSTRUCTION, template.replace("{records}", records_json))
            status = "ok"
        except LLMError as e:
            log.warning("llm: %s; publishing fallback digest", e)
            status = "fallback"
        except Exception as e:  # backstop: the LLM must never fail a run (design §7)
            log.warning("llm: unexpected %s; publishing fallback digest", type(e).__name__)
            status = "fallback"
        if body is not None:
            # Anything the model skipped is still published, un-summarised — never silently lost.
            missing = [i for i in items[:limit] if i.id not in body]
            if missing:
                log.warning("llm: %d item(s) missing from summary; appending as links", len(missing))
                body += "\n\n### Not covered by the summary\n\n" + "\n".join(_bullet(i) for i in missing)

    if body is None:
        body = (
            "*Un-summarised digest: the summariser was unavailable for this run, "
            "so this lists the records without prose.*\n\n" + "\n".join(_bullet(i) for i in items[:limit])
        )
    if overflow:
        body += "\n\n### Also included (not summarised)\n\n" + "\n".join(_bullet(i) for i in items[limit:])
    markdown_text = body + footer_md(cfg)

    digest = Digest(
        topic=topic.id,
        run_id=run_id,
        created_utc=now,
        title=digest_title(topic, now, cfg.site.timezone),
        summarised=status == "ok",
        markdown=markdown_text,
        html=sanitise(markdown_text, allowed, keep_text_for=own_urls),
        items=items,
        sources=sorted({s for v in vulns for s in v.sources}),
    )
    return digest, status
